import { readFileSync, writeFileSync } from "node:fs";
import { pages } from "../src/site.ts";
import { SITE_URL } from "../src/config.ts";

const escape = (value) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
const check = process.argv.includes("--check");
function output(path, contents) {
  const url = new URL(`../${path}`, import.meta.url);
  if (check) {
    if (readFileSync(url, "utf8").replaceAll("\r\n", "\n") !== contents) throw new Error(`${path} is stale; run npm run generate:pages`);
  } else writeFileSync(url, contents);
}

for (const page of pages) {
  const title = escape(page.title);
  const description = escape(page.description);
  const url = `${SITE_URL}${page.path}`;
  output(page.file, `<!doctype html>
<!-- Generated by scripts/generate-pages.mjs from src/site.ts. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#080a0a" />
    <meta name="description" content="${description}" />
    <meta property="og:title" content="${title}" />
    <meta property="og:description" content="${description}" />
    <meta property="og:type" content="website" />
    <meta property="og:url" content="${url}" />
    <meta property="og:site_name" content="JARVIS" />
    <meta name="twitter:card" content="summary" />
    <meta name="twitter:title" content="${title}" />
    <meta name="twitter:description" content="${description}" />
    <link rel="canonical" href="${url}" />
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <title>${title}</title>
  </head>
  <body>
    <div id="root"></div>
    <noscript>Enable JavaScript to view this page, or <a href="https://github.com/props-nothing/jarvis-core/tree/main/docs">read the JARVIS documentation</a>.</noscript>
    <script type="module" src="/src/entries/${page.id}.tsx"></script>
  </body>
</html>
`);
}

output("public/sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((page) => `  <url><loc>${SITE_URL}${page.path}</loc></url>`).join("\n")}
</urlset>
`);
console.log(`${check ? "Checked" : "Generated"} ${pages.length} pages and sitemap.`);
